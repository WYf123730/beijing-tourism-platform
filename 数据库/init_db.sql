    `id` INT NOT NULL AUTO_INCREMENT COMMENT '景点ID',
    `name` VARCHAR(100) NOT NULL COMMENT '景点名称',
    `description` TEXT COMMENT '景点描述',
    `address` VARCHAR(255) DEFAULT '' COMMENT '详细地址',
    `longitude` DOUBLE NOT NULL COMMENT '经度(GCJ-02)',
    `latitude` DOUBLE NOT NULL COMMENT '纬度(GCJ-02)',
    `category` VARCHAR(50) DEFAULT '' COMMENT '景点主分类: cultural/urban/natural',
    `subcategory` VARCHAR(50) DEFAULT '' COMMENT '景点子分类: museum/park/school/landmark/temple/street/palace/other',
    `images` TEXT COMMENT '图片URL数组(JSON字符串)',
    `phone` VARCHAR(20) DEFAULT '' COMMENT '联系电话',
    `open_time` VARCHAR(100) DEFAULT '' COMMENT '开放时间',
    `ticket_price` VARCHAR(50) DEFAULT '' COMMENT '门票价格描述',
    `rating` DOUBLE DEFAULT 0.0 COMMENT '评分',
    `is_deleted` TINYINT(1) DEFAULT 0 COMMENT '软删除标志',
